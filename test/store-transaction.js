// 存档写入故障注入：只使用本进程内的平台桩，不读取设备数据。
const assert = require('assert');
let failWrites = false;
const data = {};
global.wx = {
  getStorageSync(key) { return data[key]; },
  setStorageSync(key, value) {
    if (failWrites) throw new Error('injected storage failure');
    data[key] = JSON.parse(JSON.stringify(value));
  }
};
const store = require('../utils/store');
store.load();
let state = store.getState();
const seq = state.battle.nextSeq;
failWrites = true;
const beginFail = store.beginBattle({ mode: 'campaign', index: 1, referenceLevel: 1 });
assert.strictEqual(beginFail.ok, false);
assert.strictEqual(state.battle.pending, null);
assert.strictEqual(state.battle.nextSeq, seq);
failWrites = false;
const begin = store.beginBattle({ mode: 'campaign', index: 1, referenceLevel: 1 });
assert.ok(begin.ok);
const gold = state.res.gold;
failWrites = true;
assert.strictEqual(store.settleBattle(begin.id, { win: true }).ok, false);
assert.strictEqual(state.battle.pending.id, begin.id);
assert.strictEqual(state.res.gold, gold);
assert.strictEqual(store.interruptBattle(begin.id).ok, false);
assert.strictEqual(state.battle.pending.id, begin.id);
failWrites = false;
const settled = store.settleBattle(begin.id, { win: true });
assert.ok(settled.ok && !settled.alreadySettled);
const after = state.res.gold;
assert.ok(store.settleBattle(begin.id, { win: true }).alreadySettled);
assert.strictEqual(state.res.gold, after);
// 聚合领取写入失败时恢复资源和领取标记。
state.idle.last = Date.now() - 3600 * 1000;
const claimedBefore = state.daily.claimed.slice(), resourcesBefore = JSON.stringify(state.res);
failWrites = true;
assert.strictEqual(store.claimFreeRewards().ok, false);
assert.deepStrictEqual(state.daily.claimed, claimedBefore);
assert.strictEqual(JSON.stringify(state.res), resourcesBefore);
failWrites = false;
const gemsBeforeFast = state.res.gem, goldBeforeFast = state.res.gold, fastCountBefore = state.fast.count;
failWrites = true;
assert.strictEqual(store.fastReward(false).ok, false);
assert.strictEqual(state.res.gem, gemsBeforeFast);
assert.strictEqual(state.res.gold, goldBeforeFast);
assert.strictEqual(state.fast.count, fastCountBefore);
failWrites = false;
const paidFast = store.fastReward(false);
assert.ok(paidFast.ok);
assert.strictEqual(state.res.gem, gemsBeforeFast - require('../utils/config').FAST_REWARD_COST);
assert.strictEqual(state.fast.count, fastCountBefore + 1);
const scrollBeforeSummon = state.res.scroll, rosterBeforeSummon = JSON.stringify(state.roster);
failWrites = true;
assert.strictEqual(store.doSummon('scroll1').ok, false);
assert.strictEqual(state.res.scroll, scrollBeforeSummon);
assert.strictEqual(JSON.stringify(state.roster), rosterBeforeSummon);
failWrites = false;
const item = require('../utils/items').SHOP_GOODS[0], gemBeforeShop = state.res.gem, boughtBefore = state.buyLog.buys[item.id] || 0;
failWrites = true;
assert.strictEqual(store.buyGood(item.id).ok, false);
assert.strictEqual(state.res.gem, gemBeforeShop);
assert.strictEqual(state.buyLog.buys[item.id] || 0, boughtBefore);
failWrites = false;
assert.ok(store.buyGood(item.id).ok);
assert.strictEqual(state.res.gem, gemBeforeShop - item.price);
assert.strictEqual(state.buyLog.buys[item.id], boughtBefore + 1);
console.log('store-transaction: 30 assertions passed');
